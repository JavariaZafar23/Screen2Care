-- =====================================================================
-- Heads-up to the surgical and oncology team (Tumor Board) as soon as a
-- BI-RADS 4/5 result opens a care loop, before any biopsy is done.
-- Safe to run again on an existing database:
--   docker exec -i screening_db psql -U loop -d screening_care_loop < db/09_oncology_notice.sql
-- =====================================================================
SET TIME ZONE 'UTC';

CREATE TABLE IF NOT EXISTS team_notification (
    notification_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    episode_id      INT NOT NULL REFERENCES care_episode(episode_id),
    routed_to_role  VARCHAR(30) NOT NULL,
    message         VARCHAR(300) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    seen_at         TIMESTAMPTZ,
    seen_by         INT REFERENCES staff(staff_id),
    resolved_at     TIMESTAMPTZ,              -- benign result or treatment started
    CONSTRAINT uq_notification_episode_role UNIQUE (episode_id, routed_to_role)
);
CREATE INDEX IF NOT EXISTS ix_team_notification_open ON team_notification(routed_to_role) WHERE resolved_at IS NULL;

-- Backfill: care loops that are already open get their notification too
INSERT INTO team_notification (patient_id, episode_id, routed_to_role, message, created_at)
SELECT e.patient_id, e.episode_id, 'TumorBoard',
       'BI-RADS ' || i.birads_category || ' (' || i.modality || '): urgent workup opened. '
       || 'Biopsy pending; be ready for a possible oncology referral.',
       e.opened_at
FROM care_episode e
JOIN imaging_result i ON i.imaging_id = e.trigger_imaging_id
WHERE e.status IN ('Open','Paused')
ON CONFLICT (episode_id, routed_to_role) DO NOTHING;
