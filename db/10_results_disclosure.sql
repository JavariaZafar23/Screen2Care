-- =====================================================================
-- Telling the patient their biopsy result.
-- The patient page says "your report is ready" as soon as pathology is filed, but the
-- result itself appears only after a doctor has discussed it with the patient,
-- normally at a results appointment booked for that purpose.
-- Safe to run again on an existing database:
--   docker exec -i screening_db psql -U loop -d screening_care_loop < db/10_results_disclosure.sql
-- =====================================================================
SET TIME ZONE 'UTC';

-- Who told the patient, when, and how
ALTER TABLE pathology_result ADD COLUMN IF NOT EXISTS disclosed_at       TIMESTAMPTZ;
ALTER TABLE pathology_result ADD COLUMN IF NOT EXISTS disclosed_by       INT REFERENCES staff(staff_id);
ALTER TABLE pathology_result ADD COLUMN IF NOT EXISTS disclosure_channel VARCHAR(8)
    CHECK (disclosure_channel IN ('InPerson','Phone'));

-- Appointment with a doctor to go through the biopsy result
CREATE TABLE IF NOT EXISTS results_appointment (
    appointment_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    episode_id      INT NOT NULL REFERENCES care_episode(episode_id),
    pathology_id    INT NOT NULL REFERENCES pathology_result(pathology_id),
    clinician_id    INT NOT NULL REFERENCES staff(staff_id),
    scheduled_for   TIMESTAMPTZ NOT NULL,
    status          VARCHAR(10) NOT NULL DEFAULT 'Booked'
        CHECK (status IN ('Booked','Completed','Cancelled')),
    booked_by       INT REFERENCES staff(staff_id),
    booked_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at    TIMESTAMPTZ
);
-- At most one live appointment per report (rebooking moves it)
CREATE UNIQUE INDEX IF NOT EXISTS ux_results_appt_one_booked
    ON results_appointment(pathology_id) WHERE status = 'Booked';
