-- =====================================================================
-- Imaging follow-up loop: a separate loop for patients whose next step is more imaging
-- (BI-RADS 0 recall, BI-RADS 3 six-month scan, annual / dense / high-risk screening).
-- BI-RADS 4/5 patients stay in the care loop (care_episode, S1-S5).
--
--   R1  reminder sent            -> patient confirms        14 days  -> Navigator
--   R2  patient confirmed        -> imaging booked          due date -> Scheduling Manager
--   R3  imaging booked           -> scan done               due date + grace -> Navigator
--   R4  scan done                -> result reported         3 days   -> Clinician
--
-- Safe to run again on an existing database:
--   docker exec -i screening_db psql -U loop -d screening_care_loop < db/13_followup_loop.sql
-- =====================================================================
SET TIME ZONE 'UTC';

CREATE TABLE IF NOT EXISTS followup_loop (
    loop_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id         VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    lane               VARCHAR(25) NOT NULL,             -- lane that asked for the imaging
    source_imaging_id  INT REFERENCES imaging_result(imaging_id),
    due_date           DATE NOT NULL,                    -- when the next imaging is due
    status             VARCHAR(25) NOT NULL DEFAULT 'Scheduled'
        CHECK (status IN ('Scheduled','Open','Closed-Completed','Closed-Escalated',
                          'Closed-LostToFollowUp','Closed-Declined','Closed-Transferred','Closed-Deceased')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    opened_at          TIMESTAMPTZ,                      -- reminder sent: the R1 clock starts
    closed_at          TIMESTAMPTZ,
    closed_by          INT REFERENCES staff(staff_id),
    closure_note       VARCHAR(400),
    result_imaging_id  INT REFERENCES imaging_result(imaging_id),
    reopened_from      INT REFERENCES followup_loop(loop_id)   -- restarted after a closure
);
ALTER TABLE followup_loop ADD COLUMN IF NOT EXISTS reopened_from INT REFERENCES followup_loop(loop_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_followup_one_active ON followup_loop(patient_id) WHERE status IN ('Scheduled','Open');
CREATE INDEX IF NOT EXISTS ix_followup_source ON followup_loop(source_imaging_id);

CREATE TABLE IF NOT EXISTS followup_task (
    task_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loop_id       INT NOT NULL REFERENCES followup_loop(loop_id),
    step          SMALLINT NOT NULL CHECK (step BETWEEN 1 AND 4),
    started_at    TIMESTAMPTZ NOT NULL,
    due_at        TIMESTAMPTZ NOT NULL,
    completed_at  TIMESTAMPTZ,
    status        VARCHAR(10) NOT NULL DEFAULT 'Running' CHECK (status IN ('Running','Met','Breached','Cancelled')),
    CONSTRAINT uq_followup_task UNIQUE (loop_id, step)
);

CREATE TABLE IF NOT EXISTS followup_alert (
    alert_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id         INT NOT NULL REFERENCES followup_task(task_id) UNIQUE,
    patient_id      VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    step            SMALLINT NOT NULL,
    routed_to_role  VARCHAR(30) NOT NULL,
    action_text     VARCHAR(300) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at     TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS followup_contact (
    contact_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loop_id       INT NOT NULL REFERENCES followup_loop(loop_id),
    channel       VARCHAR(8) NOT NULL CHECK (channel IN ('SMS','Phone','Email','InPerson','Letter','Portal')),
    outcome       VARCHAR(12) CHECK (outcome IN ('Reached','NoAnswer','WrongNumber','Declined')),
    attempted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    performed_by  INT REFERENCES staff(staff_id)
);

CREATE TABLE IF NOT EXISTS followup_appointment (
    appointment_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loop_id         INT NOT NULL REFERENCES followup_loop(loop_id),
    modality        VARCHAR(12) NOT NULL CHECK (modality IN ('Mammogram','DBT','Ultrasound','MRI')),
    scheduled_for   TIMESTAMPTZ NOT NULL,
    status          VARCHAR(10) NOT NULL DEFAULT 'Booked' CHECK (status IN ('Booked','Performed','Cancelled')),
    booked_by       INT REFERENCES staff(staff_id),
    booked_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    performed_at    TIMESTAMPTZ
);

-- Existing patients: one scheduled loop for every current imaging lane with a due date
-- (BI-RADS 4/5 patients with an open care loop are left out).
INSERT INTO followup_loop (patient_id, lane, source_imaging_id, due_date)
SELECT la.patient_id, la.lane,
       (SELECT i.imaging_id FROM imaging_result i WHERE i.patient_id = la.patient_id
        ORDER BY i.result_released_at DESC, i.birads_category DESC LIMIT 1),
       la.next_due_date
FROM lane_assignment la
WHERE la.is_current AND la.next_due_date IS NOT NULL
  AND la.lane IN ('RecallBirads0','ShortInterval6M','RoutineScreening','DenseSupplemental',
                  'HighRisk-MRIOnly','HighRisk-DBT+MRI','HighRisk-DBT+ConsiderMRI')
  AND NOT EXISTS (SELECT 1 FROM care_episode e WHERE e.patient_id = la.patient_id AND e.status IN ('Open','Paused'))
  AND NOT EXISTS (SELECT 1 FROM followup_loop f WHERE f.patient_id = la.patient_id);
