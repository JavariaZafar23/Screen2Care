-- SLA loop: breach alerts routed to a role, and logins for the escalation roles.
-- Safe to run again on an existing database:
--   docker exec -i screening_db psql -U loop -d screening_care_loop < db/07_sla.sql
-- =====================================================================
SET TIME ZONE 'UTC';

-- Logins for the roles that receive SLA escalations
ALTER TABLE app_user DROP CONSTRAINT IF EXISTS app_user_role_check;
ALTER TABLE app_user ADD CONSTRAINT app_user_role_check CHECK (role IN (
  'Admin','Clinician','Radiologist','Pathologist','Navigator','CMO',
  'SchedulingManager','LabDirector','TumorBoard','Patient'));

-- Section 2: 7 days from the patient acknowledging the result, met once a biopsy is booked
UPDATE sla_definition
SET name = 'Biopsy booked', clock_start_event = 'PatientAcknowledged', completion_event = 'BiopsyBooked'
WHERE section = 2;

-- One alert per breached SLA task, sent to the role in sla_definition.escalation1_role.
-- It stays open until the task is completed (resolved_at), even after someone has seen it.
CREATE TABLE IF NOT EXISTS sla_alert (
    alert_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sla_task_id     INT NOT NULL REFERENCES sla_task(sla_task_id),
    patient_id      VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    section         SMALLINT NOT NULL REFERENCES sla_definition(section),
    level           SMALLINT NOT NULL DEFAULT 1,
    routed_to_role  VARCHAR(30) NOT NULL,
    action_text     VARCHAR(300) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    seen_at         TIMESTAMPTZ,
    seen_by         INT REFERENCES staff(staff_id),
    resolved_at     TIMESTAMPTZ,
    CONSTRAINT uq_alert_task_level UNIQUE (sla_task_id, level)
);
CREATE INDEX IF NOT EXISTS ix_sla_alert_open ON sla_alert(routed_to_role) WHERE resolved_at IS NULL;
