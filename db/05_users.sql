-- Login accounts. Each account is either a staff member or a patient, never both.
CREATE TABLE app_user (
    user_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(60)  NOT NULL UNIQUE,
    password_hash  VARCHAR(200) NOT NULL,
    role           VARCHAR(20)  NOT NULL
        CHECK (role IN ('Admin','Clinician','Radiologist','Pathologist','Navigator','CMO','Patient')),
    staff_id       INT REFERENCES staff(staff_id),
    patient_id     VARCHAR(20) REFERENCES patient(patient_id),
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_user_one_link CHECK ((staff_id IS NULL) <> (patient_id IS NULL))
);
