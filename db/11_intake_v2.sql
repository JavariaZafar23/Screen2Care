SET TIME ZONE 'UTC';

-- Section 3/4: obstetric, radiation and breastfeeding details
ALTER TABLE patient_risk_profile
    ADD COLUMN IF NOT EXISTS marital_status VARCHAR(10)
        CHECK (marital_status IN ('Married','Unmarried')),
    ADD COLUMN IF NOT EXISTS chest_radiation_status VARCHAR(7)
        CHECK (chest_radiation_status IN ('Yes','No','Unknown')),
    ADD COLUMN IF NOT EXISTS chest_radiation_years SMALLINT
        CHECK (chest_radiation_years BETWEEN 0 AND 100),
    ADD COLUMN IF NOT EXISTS breastfeeding_history_status VARCHAR(7)
        CHECK (breastfeeding_history_status IN ('Yes','No','Unknown')),
    ADD COLUMN IF NOT EXISTS breastfeeding_duration_years NUMERIC(4,1);

-- Section 5: each relative's known mutation
ALTER TABLE family_history
    ADD COLUMN IF NOT EXISTS known_genetic_mutations VARCHAR(8) NOT NULL DEFAULT 'Unknown';
ALTER TABLE family_history DROP CONSTRAINT IF EXISTS family_history_known_genetic_mutations_check;
ALTER TABLE family_history ADD CONSTRAINT family_history_known_genetic_mutations_check
    CHECK (known_genetic_mutations IN ('BRCA1','BRCA2','Negative','Unknown'));

-- Section 6: "Not answered" is stored as NULL, never as normal
ALTER TABLE clinical_breast_exam
    ALTER COLUMN inspection_normal DROP NOT NULL,
    ALTER COLUMN mass_present DROP NOT NULL,
    ALTER COLUMN axillary_node_palpable DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS nipple_discharge_color VARCHAR(6)
        CHECK (nipple_discharge_color IN ('None','Bloody','Clear','Milky')),
    ADD COLUMN IF NOT EXISTS skin_change VARCHAR(20)
        CHECK (skin_change IN ('Dimpling','Retraction','Scaling / rash'));

-- Section 7: one row per scan, with the date it was performed
ALTER TABLE imaging_result ADD COLUMN IF NOT EXISTS performed_date DATE;

-- Sections 4 and 8 on the encounter
ALTER TABLE encounter
    ADD COLUMN IF NOT EXISTS medical_history_details TEXT,
    ADD COLUMN IF NOT EXISTS plan_options TEXT[],
    ADD COLUMN IF NOT EXISTS clinician_notes TEXT,
    ADD COLUMN IF NOT EXISTS idempotency_key VARCHAR(100);
-- A double-click on Save must not create two visits
CREATE UNIQUE INDEX IF NOT EXISTS ux_encounter_idempotency_key
    ON encounter(idempotency_key) WHERE idempotency_key IS NOT NULL;

-- Exact, unchangeable copy of every submitted form (shown as "previous intakes")
CREATE TABLE IF NOT EXISTS encounter_snapshot (
    snapshot_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id    VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    encounter_id  INT NOT NULL UNIQUE REFERENCES encounter(encounter_id),
    payload       JSONB NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_encounter_snapshot_patient ON encounter_snapshot(patient_id, created_at DESC);

CREATE OR REPLACE FUNCTION reject_snapshot_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'encounter snapshots are immutable';
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS encounter_snapshot_immutable ON encounter_snapshot;
CREATE TRIGGER encounter_snapshot_immutable BEFORE UPDATE ON encounter_snapshot
    FOR EACH ROW EXECUTE FUNCTION reject_snapshot_mutation();

-- First-visit risk tier calculated from the snapshot (High / Medium / Low / Incomplete)
CREATE TABLE IF NOT EXISTS risk_assessment (
    risk_assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id   INT NOT NULL UNIQUE REFERENCES encounter(encounter_id),
    patient_id     VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    snapshot_id    BIGINT NOT NULL UNIQUE REFERENCES encounter_snapshot(snapshot_id),
    tier           VARCHAR(20) NOT NULL CHECK (tier IN ('High','Medium','Low','Incomplete')),
    reasons        JSONB NOT NULL,
    rules_version  VARCHAR(100) NOT NULL,
    examiner_name  VARCHAR(150) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_risk_assessment_patient ON risk_assessment(patient_id, created_at DESC);

-- Due dates for each plan option the doctor picked
CREATE TABLE IF NOT EXISTS plan_items (
    plan_item_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id    VARCHAR(20) NOT NULL REFERENCES patient(patient_id),
    encounter_id  INT NOT NULL REFERENCES encounter(encounter_id),
    plan_option   VARCHAR(120) NOT NULL,
    due_date      DATE,
    status        VARCHAR(10) NOT NULL DEFAULT 'Planned' CHECK (status IN ('Planned','Completed','Cancelled')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_plan_items_due ON plan_items(status, due_date);
