-- =====================================================================
-- Self sign-up. Patients are matched to their hospital record and get an account at once.
-- Staff requests wait here until an admin approves them (then a staff row + login are created).
-- Safe to run again:
--   docker exec -i screening_db psql -U loop -d screening_care_loop < db/08_signup.sql
-- =====================================================================
CREATE TABLE IF NOT EXISTS signup_request (
    request_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(60)  NOT NULL,
    password_hash  VARCHAR(200) NOT NULL,
    full_name      VARCHAR(150) NOT NULL,
    role           VARCHAR(20)  NOT NULL
        CHECK (role IN ('Clinician','Radiologist','Pathologist','Navigator','CMO',
                        'SchedulingManager','LabDirector','TumorBoard')),
    requested_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    status         VARCHAR(10)  NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected')),
    decided_at     TIMESTAMPTZ,
    decided_by     INT REFERENCES staff(staff_id)
);
-- A username can only be waiting for approval once
CREATE UNIQUE INDEX IF NOT EXISTS ux_signup_pending_username ON signup_request(lower(username)) WHERE status = 'Pending';

-- One patient login per patient record
CREATE UNIQUE INDEX IF NOT EXISTS ux_app_user_patient ON app_user(patient_id) WHERE patient_id IS NOT NULL;
